import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { PolyrouteError } from "../errors.js";
import { createQueue, runTool, samePath } from "./process.js";
import type { Language, RouteBuildInput, RouteBuildResult } from "./types.js";

export const RUST_TARGET = "wasm32-wasip2";
export const WSTD_VERSION = "0.5";

interface CargoArtifact {
  reason?: string;
  target?: { kind?: string[]; src_path?: string };
  executable?: string | null;
  filenames?: string[];
}

// cargo locks the shared target directory anyway; queueing here keeps one
// build's artifact from being read while the next build overwrites it.
const enqueue = createQueue();

export const rust: Language = {
  name: "Rust",
  extensions: [".rs"],
  handlerHint: "Mark the route's entry point with `#[wstd::http_server]`.",
  build: (input) => buildRustRoute(input),
};

export function buildRustRoute(input: RouteBuildInput): Promise<RouteBuildResult> {
  return enqueue(() => build(input));
}

async function build({
  routeFile,
  label,
  cacheDir,
  root,
}: RouteBuildInput): Promise<RouteBuildResult> {
  const routeDir = path.dirname(routeFile);
  const ownManifest = path.join(routeDir, "Cargo.toml");
  const manifestPath = existsSync(ownManifest)
    ? ownManifest
    : await writeGeneratedManifest(routeFile, label, cacheDir);
  const targetDir = path.join(cacheDir, "target");

  const result = await runTool(
    "cargo",
    [
      "build",
      "--release",
      "--target",
      RUST_TARGET,
      "--manifest-path",
      manifestPath,
      "--message-format=json-render-diagnostics",
    ],
    {
      env: { CARGO_TARGET_DIR: targetDir },
      missing: `Building \`${label}\` needs the Rust toolchain, but \`cargo\` isn't on PATH. Install it from https://rustup.rs, then run \`rustup target add ${RUST_TARGET}\`.`,
    },
  );

  if (result.exitCode !== 0) {
    const output = result.stderr.trimEnd();
    if (
      output.includes(RUST_TARGET) &&
      /target may not be installed|can't find crate for `(std|core)`/.test(output)
    ) {
      throw new PolyrouteError(
        "TARGET_MISSING",
        `Building \`${label}\` needs the \`${RUST_TARGET}\` Rust target. Install it with \`rustup target add ${RUST_TARGET}\`.\n\n${output}`,
      );
    }
    throw new PolyrouteError("BUILD_FAILED", `cargo couldn't build \`${label}\`:\n\n${output}`);
  }

  const executable = findExecutable(result.stdout, routeFile);
  if (executable === undefined) {
    throw new PolyrouteError(
      "BUILD_FAILED",
      `cargo built \`${label}\` but produced no Wasm binary for it. When a route has its own Cargo.toml, declare the route as a binary: \`[[bin]] name = "route" path = "${path.basename(routeFile)}"\`.`,
    );
  }

  const wasm = await readFile(executable);
  const sources = await readDepInfo(executable.replace(/\.wasm$/, ".d"), routeDir, root, cacheDir);
  if (manifestPath === ownManifest) sources.push(ownManifest);
  return { wasm, sources };
}

async function writeGeneratedManifest(
  routeFile: string,
  label: string,
  cacheDir: string,
): Promise<string> {
  const id = createHash("sha256").update(routeFile).digest("hex").slice(0, 12);
  const crateDir = path.join(cacheDir, "crates", id);
  const manifestPath = path.join(crateDir, "Cargo.toml");
  const manifest = [
    `# Generated by polyroute for ${label}. Changes are overwritten.`,
    "[package]",
    `name = "polyroute-${id}"`,
    'version = "0.0.0"',
    'edition = "2024"',
    "publish = false",
    "",
    "[[bin]]",
    `name = "route-${id}"`,
    `path = ${JSON.stringify(routeFile)}`,
    "",
    "[dependencies]",
    `wstd = "${WSTD_VERSION}"`,
    "",
    "[workspace]",
    "",
  ].join("\n");

  await mkdir(crateDir, { recursive: true });
  const current = await readFile(manifestPath, "utf8").catch(() => undefined);
  // Rewriting an unchanged manifest would bump its mtime and make cargo rebuild.
  if (current !== manifest) await writeFile(manifestPath, manifest);
  return manifestPath;
}

function findExecutable(stdout: string, routeFile: string): string | undefined {
  for (const line of stdout.split("\n")) {
    if (!line.startsWith("{")) continue;
    let message: CargoArtifact;
    try {
      message = JSON.parse(line) as CargoArtifact;
    } catch {
      continue;
    }
    if (message.reason !== "compiler-artifact") continue;
    if (!message.target?.kind?.includes("bin") || message.target.src_path === undefined) continue;
    if (!samePath(message.target.src_path, routeFile)) continue;
    return message.executable ?? message.filenames?.find((file) => file.endsWith(".wasm"));
  }
  return undefined;
}

function isInside(directory: string, file: string): boolean {
  const relative = path.relative(directory, file);
  return relative !== ".." && !relative.startsWith(".." + path.sep) && !path.isAbsolute(relative);
}

/** Cargo lists local path crates and generated build inputs together. Only watch source inputs. */
async function readDepInfo(
  depInfoPath: string,
  routeDir: string,
  root: string | undefined,
  cacheDir: string,
): Promise<string[]> {
  const content = await readFile(depInfoPath, "utf8").catch(() => undefined);
  if (content === undefined) return [];
  const firstLine = content.split("\n", 1)[0] ?? "";
  const separator = firstLine.indexOf(": ");
  if (separator === -1) return [];
  // Rust can spell an explicit #[path] relative to the handler, including "..".
  // Keep those module dependencies even when the route lives outside the app root.
  const routePrefix = routeDir.endsWith(path.sep) ? routeDir : routeDir + path.sep;
  return firstLine
    .slice(separator + 2)
    .split(/(?<!\\) /)
    .map((file) => file.replaceAll("\\ ", " ").trim())
    .filter(
      (file) =>
        path.isAbsolute(file) &&
        !isInside(cacheDir, file) &&
        (file.startsWith(routePrefix) || (root !== undefined && isInside(root, file))),
    );
}
