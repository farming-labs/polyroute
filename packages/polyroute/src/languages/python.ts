import { createHash, randomUUID } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PolyrouteError } from "../errors.js";
import { createQueue, runTool } from "./process.js";
import type { Language, RouteBuildInput, RouteBuildResult } from "./types.js";

/** polyroute's Python modules, shipped in the package. */
export const PYTHON_DIR = fileURLToPath(new URL("../../python/", import.meta.url));
/** The WIT worlds Python routes are built against, shipped in the package. */
export const WIT_DIR = fileURLToPath(new URL("../../wit/", import.meta.url));
export const ROUTE_WORLD = "polyroute:route/route";
/** `ROUTE_WORLD` plus `wasi:http/outgoing-handler`, for routes that send requests. */
export const OUTBOUND_ROUTE_WORLD = "polyroute:route/outbound-route";

const APP_MODULE = "polyroute_app";
const MODULE_NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;
const IGNORED_DIRS = new Set(["__pycache__", "node_modules", "site-packages"]);
// componentize-py imports every interface in the world, whether or not the code
// uses it, so a route is built with `wasi:http/outgoing-handler` only when one
// of its files imports a module that sends requests or uses the binding itself.
const SENDS_REQUESTS =
  /^[ \t]*(?:from|import)[ \t]+(?:polyroute_fetch|poll_loop)\b|\boutgoing_handler\b/m;

const enqueue = createQueue();

export const python: Language = {
  name: "Python",
  extensions: [".py"],
  handlerHint: "Define a function named after an HTTP method, such as `def GET(request): ...`.",
  build: (input) => enqueue(() => buildPythonRoute(input)),
};

async function buildPythonRoute({
  routeFile,
  label,
  cacheDir,
  runtime = "jco",
}: RouteBuildInput): Promise<RouteBuildResult> {
  const routeDir = path.dirname(routeFile);
  const moduleName = path.basename(routeFile, ".py");
  if (!MODULE_NAME.test(moduleName)) {
    throw new PolyrouteError(
      "BUILD_FAILED",
      `Python can't import \`${label}\` as a module, because \`${moduleName}\` isn't a valid identifier. Rename the file, for example to \`route.py\`.`,
    );
  }

  const id = createHash("sha256").update(`${routeFile}\0${runtime}`).digest("hex").slice(0, 12);
  const workDir = path.join(cacheDir, "python", id);
  await mkdir(workDir, { recursive: true });
  await writeIfChanged(
    path.join(workDir, `${APP_MODULE}.py`),
    [
      `# Generated by polyroute for ${label}. Changes are overwritten.`,
      "import importlib",
      "",
      `from ${runtime === "wasmtime" ? "polyroute_native" : "polyroute"} import create_handler`,
      "",
      `IncomingHandler = create_handler(importlib.import_module(${JSON.stringify(moduleName)}))`,
      "",
    ].join("\n"),
  );

  const sources = await listPythonSources(routeDir);
  const outbound = await anySendsRequests(sources);
  const world =
    runtime === "wasmtime"
      ? `polyroute:route/native-${outbound ? "outbound-route" : "route"}`
      : outbound
        ? OUTBOUND_ROUTE_WORLD
        : ROUTE_WORLD;
  // Each build writes its own file, as in go.ts, for builds in other processes.
  const output = path.join(workDir, `route-${randomUUID()}.wasm`);
  try {
    return await componentize(label, world, workDir, routeDir, output, sources);
  } finally {
    await rm(output, { force: true });
  }
}

async function componentize(
  label: string,
  world: string,
  workDir: string,
  routeDir: string,
  output: string,
  sources: string[],
): Promise<RouteBuildResult> {
  const result = await runTool(
    "componentize-py",
    [
      "--quiet",
      "-d",
      WIT_DIR,
      "-w",
      world,
      "componentize",
      APP_MODULE,
      "-p",
      workDir,
      "-p",
      PYTHON_DIR,
      "-p",
      routeDir,
      "-o",
      output,
    ],
    {
      missing: `Building \`${label}\` needs componentize-py, but it isn't on PATH. Install it with \`pip install componentize-py\` or \`uv tool install componentize-py\`.`,
    },
  );
  if (result.exitCode !== 0) {
    const diagnostics = `${result.stdout}${result.stderr}`.trimEnd();
    throw new PolyrouteError(
      "BUILD_FAILED",
      `componentize-py couldn't build \`${label}\`:\n\n${diagnostics}`,
    );
  }

  return { wasm: await readFile(output), sources };
}

/** Whether Python source imports `polyroute_fetch` or `poll_loop`, or uses `outgoing_handler`. */
export function sendsRequests(source: string): boolean {
  return SENDS_REQUESTS.test(source);
}

async function anySendsRequests(sources: string[]): Promise<boolean> {
  for (const source of sources) {
    if (sendsRequests(await readFile(source, "utf8"))) return true;
  }
  return false;
}

async function writeIfChanged(file: string, content: string): Promise<void> {
  const current = await readFile(file, "utf8").catch(() => undefined);
  if (current !== content) await writeFile(file, content);
}

/**
 * Every `.py` file under the route's directory, for the dev server to watch.
 * Hidden and dependency directories are skipped without being read.
 */
async function listPythonSources(dir: string): Promise<string[]> {
  const sources: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!entry.name.startsWith(".") && !IGNORED_DIRS.has(entry.name)) {
        sources.push(...(await listPythonSources(file)));
      }
    } else if (entry.name.endsWith(".py")) {
      sources.push(file);
    }
  }
  return sources;
}
